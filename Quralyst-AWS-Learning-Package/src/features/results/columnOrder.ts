export function orderResultColumns(columns: string[], preferred: string[]): string[] {
  const present = new Set(columns);
  const ordered = preferred.filter((c) => present.has(c));
  const rest = columns.filter((c) => !preferred.includes(c));
  return [...ordered, ...rest];
}
