#!/usr/bin/env node
/**
 * Load frontend VITE_* vars from AWS Secrets Manager before `vite build`.
 *
 * Local dev: leave AWS_SECRETS_ENABLED unset/false and use a manual `.env`.
 * Server/EC2: set the thin bootstrap vars (IAM role supplies credentials) and run
 * this script — it writes `.env.production` for the production Vite build.
 *
 * Secret JSON keys must be prefixed with VITE_ (public client config). Probe keys
 * for /backend-connection-testing:
 *   VITE_SECRETS_HEALTH_PROBE_A
 *   VITE_SECRETS_HEALTH_PROBE_B
 */

import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const TRUTHY = new Set(['1', 'true', 'yes', 'on']);
const DEFAULT_REGION = 'us-west-1';
const DEFAULT_SECRET_NAME = 'quralyst/dev/backend/env';
const OUTPUT_FILE = '.env.production';

function isEnabled() {
  return TRUTHY.has((process.env.AWS_SECRETS_ENABLED ?? '').trim().toLowerCase());
}

function region() {
  return (
    process.env.AWS_REGION?.trim() ||
    process.env.AWS_DEFAULT_REGION?.trim() ||
    DEFAULT_REGION
  );
}

function secretName() {
  return process.env.AWS_SECRET_NAME?.trim() || DEFAULT_SECRET_NAME;
}

function parseExistingEnv(filePath) {
  if (!existsSync(filePath)) return {};
  const out = {};
  for (const line of readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function serializeEnv(entries) {
  const lines = [
    '# Generated by scripts/load-aws-secrets.mjs — do not commit real values.',
    `# ${new Date().toISOString()}`,
    '',
  ];
  for (const [key, value] of Object.entries(entries).sort(([a], [b]) => a.localeCompare(b))) {
    const safe = String(value).replace(/\n/g, '\\n');
    lines.push(`${key}=${safe}`);
  }
  lines.push('');
  return lines.join('\n');
}

async function fetchSecretDict(name, regionName) {
  const { SecretsManagerClient, GetSecretValueCommand } = await import(
    '@aws-sdk/client-secrets-manager'
  );
  const client = new SecretsManagerClient({ region: regionName });
  const response = await client.send(new GetSecretValueCommand({ SecretId: name }));
  const raw = response.SecretString;
  if (!raw) {
    throw new Error(`Secret ${JSON.stringify(name)} has empty SecretString`);
  }
  const data = JSON.parse(raw);
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error('AWS secret must be a JSON object');
  }
  return data;
}

async function main() {
  if (!isEnabled()) {
    console.log('[load-aws-secrets] AWS_SECRETS_ENABLED is off — skipping (use local .env).');
    return;
  }

  const name = secretName();
  const regionName = region();
  console.log(`[load-aws-secrets] Fetching ${name} (${regionName})…`);

  const secret = await fetchSecretDict(name, regionName);
  const viteEntries = {};
  for (const [key, value] of Object.entries(secret)) {
    if (!key.startsWith('VITE_') || value == null) continue;
    viteEntries[key] = String(value);
  }

  if (Object.keys(viteEntries).length === 0) {
    throw new Error(
      `No VITE_* keys found in secret ${JSON.stringify(name)}. Add frontend keys to the JSON secret.`,
    );
  }

  viteEntries.VITE_SECRETS_LOADED_FROM_AWS = 'true';

  const outPath = resolve(process.cwd(), OUTPUT_FILE);
  const existing = parseExistingEnv(outPath);
  const merged = { ...viteEntries };
  for (const [key, value] of Object.entries(existing)) {
    if (value?.trim()) merged[key] = value;
  }

  writeFileSync(outPath, serializeEnv(merged), 'utf8');
  console.log(
    `[load-aws-secrets] Wrote ${Object.keys(merged).length} keys to ${OUTPUT_FILE}`,
  );
}

main().catch((err) => {
  console.error('[load-aws-secrets] Failed:', err instanceof Error ? err.message : err);
  process.exit(1);
});
